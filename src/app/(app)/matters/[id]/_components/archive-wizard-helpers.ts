import type { ArchiveChecklist, ArchiveChecklistItem } from "@/lib/archive/checklists";

/** Dữ liệu prep trả về từ getArchivePrepData (chỉ phần hook cần). */
export interface ArchivePrepResponse {
  checklist: ArchiveChecklist;
  docsByItem: Record<string, { id: string; name: string }[]>;
  matter: { closedAt: Date | null };
  existingSummary: string | null;
}

/** State prep do hook sở hữu. */
export interface PrepState {
  checklist: ArchiveChecklist | null;
  checked: Record<string, boolean>;
  linkedDocs: Record<string, { id: string; name: string }[]>;
  completedAt: string;
  summary: string;
}

/** Ngày ISO → YYYY-MM-DD (phần ngày). */
export function toDateInput(d: Date): string {
  return d.toISOString().slice(0, 10);
}

/** Tick checkbox: mục tự sinh + mục đã có tài liệu liên kết. */
export function buildAutoChecked(
  checklist: ArchiveChecklist,
  docsByItem: Record<string, unknown>
): Record<string, boolean> {
  const autoChecked: Record<string, boolean> = {};
  for (const item of checklist.items) {
    if (item.autoGenerated) autoChecked[item.id] = true;
  }
  for (const itemId of Object.keys(docsByItem)) {
    autoChecked[itemId] = true;
  }
  return autoChecked;
}

/** Áp dụng response prep vào state (thuần, không mutate). */
export function applyPrepData(state: PrepState, data: ArchivePrepResponse): PrepState {
  return {
    ...state,
    checklist: data.checklist,
    checked: buildAutoChecked(data.checklist, data.docsByItem),
    linkedDocs: data.docsByItem,
    ...(data.matter.closedAt ? { completedAt: toDateInput(data.matter.closedAt) } : {}),
    ...(data.existingSummary ? { summary: data.existingSummary } : {})
  };
}

/** Các mục bắt buộc chưa tick (thuần — dùng cho cảnh báo trước khi lưu trữ). */
export function computeMissingRequired(
  checklist: ArchiveChecklist | null,
  checked: Record<string, boolean>
): ArchiveChecklistItem[] {
  if (!checklist) return [];
  return checklist.items.filter((i) => !i.autoGenerated && i.required && !checked[i.id]);
}

/** Dựng FormData upload cho 1 mục checklist (tên file cắt extension, fallback label mục). */
export function buildArchiveUploadFormData({
  matterId,
  item,
  file
}: {
  matterId: string;
  item: ArchiveChecklistItem;
  file: File;
}): FormData {
  const fd = new FormData();
  fd.set("matterId", matterId);
  fd.set("name", file.name.replace(/\.[^.]+$/, "") || item.label);
  fd.set("category", "OTHER"); // TODO: infer from item.id
  fd.set("archiveChecklistItemId", item.id);
  fd.set("encrypted", "false");
  fd.set("file", file);
  return fd;
}
