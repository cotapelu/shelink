import { describe, it, expect } from "vitest";
import {
  buildArchiveUploadFormData,
  buildAutoChecked,
  applyPrepData,
  computeMissingRequired,
  type PrepState
} from "@/app/(app)/matters/[id]/_components/archive-wizard-helpers";
import type { ArchiveChecklist } from "@/lib/archive/checklists";

const checklist = (items: ArchiveChecklist["items"]): ArchiveChecklist =>
  ({ items }) as unknown as ArchiveChecklist;

const item = (id: string, over: Partial<ArchiveChecklist["items"][number]> = {}) =>
  ({ id, label: id, autoGenerated: false, required: false, ...over }) as ArchiveChecklist["items"][number];

describe("buildAutoChecked", () => {
  it("tick mục auto-generated và mục đã có tài liệu", () => {
    const cl = checklist([
      item("a", { autoGenerated: true }),
      item("b"),
      item("c", { autoGenerated: true })
    ]);
    expect(buildAutoChecked(cl, { b: [{ id: "d1", name: "x" }] })).toEqual({ a: true, c: true, b: true });
  });

  it("rỗng khi không có gì", () => {
    expect(buildAutoChecked(checklist([]), {})).toEqual({});
  });
});

describe("applyPrepData", () => {
  const base: PrepState = {
    checklist: null,
    checked: {},
    linkedDocs: {},
    completedAt: "2026-01-01",
    summary: ""
  };

  it("đẩy checklist/checked/linkedDocs vào state", () => {
    const cl = checklist([item("a", { autoGenerated: true })]);
    const next = applyPrepData(base, { checklist: cl, docsByItem: {}, matter: {}, existingSummary: null } as never);
    expect(next.checklist).toBe(cl);
    expect(next.checked).toEqual({ a: true });
  });

  it("ghi đè completedAt khi matter đã đóng, giữ summary khi chưa có", () => {
    const next = applyPrepData(base, {
      checklist: checklist([]),
      docsByItem: {},
      matter: { closedAt: new Date("2026-03-04T10:00:00Z") },
      existingSummary: null
    } as never);
    expect(next.completedAt).toBe("2026-03-04");
    expect(next.summary).toBe("");
  });

  it("ghi đè summary khi đã có summary cũ, giữ completedAt khi chưa đóng", () => {
    const next = applyPrepData(base, {
      checklist: checklist([]),
      docsByItem: {},
      matter: { closedAt: null },
      existingSummary: "tóm tắt cũ"
    } as never);
    expect(next.summary).toBe("tóm tắt cũ");
    expect(next.completedAt).toBe("2026-01-01");
  });

  it("không mutate state cũ", () => {
    const snapshot = { ...base };
    applyPrepData(base, { checklist: checklist([]), docsByItem: {}, matter: {}, existingSummary: "s" } as never);
    expect(base).toEqual(snapshot);
  });
});

describe("computeMissingRequired", () => {
  it("null checklist → rỗng", () => {
    expect(computeMissingRequired(null, {})).toEqual([]);
  });

  it("chỉ lấy mục bắt buộc, không auto-generated, chưa tick", () => {
    const cl = checklist([
      item("a", { required: true }),
      item("b", { required: true, autoGenerated: true }),
      item("c", { required: false }),
      item("d", { required: true })
    ]);
    const missing = computeMissingRequired(cl, { a: true });
    expect(missing.map((i) => i.id)).toEqual(["d"]);
  });

  it("tick đủ → rỗng", () => {
    const cl = checklist([item("a", { required: true }), item("b", { required: true })]);
    expect(computeMissingRequired(cl, { a: true, b: true })).toEqual([]);
  });
});

describe("buildArchiveUploadFormData", () => {
  it("dựng FormData đúng các trường cho upload tài liệu checklist", () => {
    const file = new File(["x"], "Bản scan.pdf", { type: "application/pdf" });
    const fd = buildArchiveUploadFormData({
      matterId: "m1",
      item: item("CONTRACT", { label: "Hợp đồng" }),
      file
    });
    expect(fd.get("matterId")).toBe("m1");
    expect(fd.get("name")).toBe("Bản scan"); // cắt phần mở rộng
    expect(fd.get("category")).toBe("OTHER");
    expect(fd.get("archiveChecklistItemId")).toBe("CONTRACT");
    expect(fd.get("encrypted")).toBe("false");
    expect(fd.get("file")).toBe(file);
  });

  it("tên rỗng sau khi cắt extension → fallback label mục", () => {
    const file = new File(["x"], ".hidden", { type: "application/octet-stream" });
    const fd = buildArchiveUploadFormData({ matterId: "m1", item: item("DOC", { label: "Nhãn mục" }), file });
    expect(fd.get("name")).toBe("Nhãn mục");
  });
});
